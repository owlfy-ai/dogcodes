//! Bounded, cancellable portal FD IO. A clipboard provider must not be able to
//! block the authorization actor on a full pipe or kill Core with SIGPIPE.
use crate::Result;
use std::{
    io,
    os::fd::{AsRawFd, OwnedFd},
};
use tokio::io::unix::AsyncFd;

pub(super) struct Channel {
    fd: AsyncFd<OwnedFd>,
    socket: bool,
}
impl Channel {
    pub(super) fn new(fd: OwnedFd) -> Result<Self> {
        // SAFETY: stat is writable and the owned FD remains live throughout.
        let mut stat: libc::stat = unsafe { std::mem::zeroed() };
        // SAFETY: both arguments identify live storage.
        if unsafe { libc::fstat(fd.as_raw_fd(), &mut stat) } != 0 {
            return Err("剪贴板数据通道无效".into());
        }
        let kind = stat.st_mode & libc::S_IFMT;
        if kind != libc::S_IFIFO && kind != libc::S_IFSOCK {
            return Err("系统返回了不支持的剪贴板数据通道".into());
        }
        // SAFETY: fcntl reads/sets flags on the live owned FD, without pointers.
        let flags = unsafe { libc::fcntl(fd.as_raw_fd(), libc::F_GETFL) };
        if flags < 0 {
            return Err("无法读取剪贴板通道标志".into());
        }
        // SAFETY: this only adds nonblocking mode to a live FD, preserving flags.
        let changed =
            unsafe { libc::fcntl(fd.as_raw_fd(), libc::F_SETFL, flags | libc::O_NONBLOCK) };
        if changed < 0 {
            return Err("无法设置剪贴板非阻塞传输".into());
        }
        Ok(Self {
            fd: AsyncFd::new(fd).map_err(|_| "无法监听剪贴板数据通道")?,
            socket: kind == libc::S_IFSOCK,
        })
    }
    pub(super) async fn write(&self, mut bytes: &[u8], active: impl Fn() -> bool) -> Result<()> {
        while !bytes.is_empty() {
            if !active() {
                return Err("剪贴板授权已结束".into());
            }
            let mut ready = self.fd.writable().await.map_err(|_| "剪贴板写入中断")?;
            let result = ready.try_io(|fd| {
                if !active() {
                    return Err(io::Error::from(io::ErrorKind::PermissionDenied));
                }
                if self.socket {
                    // SAFETY: bytes is readable and MSG_NOSIGNAL is per-call.
                    count(unsafe {
                        libc::send(
                            fd.as_raw_fd(),
                            bytes.as_ptr().cast(),
                            bytes.len(),
                            libc::MSG_NOSIGNAL,
                        )
                    })
                } else {
                    pipe_write(fd.as_raw_fd(), bytes)
                }
            });
            match result {
                Ok(Ok(0)) => return Err("剪贴板接收端已关闭".into()),
                Ok(Ok(n)) => bytes = &bytes[n..],
                Ok(Err(e)) if e.kind() == io::ErrorKind::Interrupted => continue,
                Ok(Err(_)) => return Err("剪贴板写入失败".into()),
                Err(_) => {}
            }
        }
        Ok(())
    }
}
fn count(n: isize) -> io::Result<usize> {
    if n < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(n as usize)
    }
}
fn pipe_write(fd: i32, bytes: &[u8]) -> io::Result<usize> {
    // Block only this thread, only around the synchronous syscall. No await or
    // global signal-handler changes occur under the mask. Preserve old pending
    // SIGPIPE; consume only one generated by this particular broken-pipe write.
    // SAFETY: all signal sets are initialized before being read by libc.
    let (mut set, mut old, mut pending): (libc::sigset_t, libc::sigset_t, libc::sigset_t) =
        unsafe { std::mem::zeroed() };
    // SAFETY: pointers refer to writable/live initialized signal sets.
    unsafe {
        libc::sigemptyset(&mut set);
        libc::sigaddset(&mut set, libc::SIGPIPE);
    }
    // SAFETY: this thread's mask is copied to old and restored before return.
    let status = unsafe { libc::pthread_sigmask(libc::SIG_BLOCK, &set, &mut old) };
    if status != 0 {
        return Err(io::Error::from_raw_os_error(status));
    }
    // SAFETY: pending is writable, the signal number is valid.
    let was_pending = unsafe {
        libc::sigpending(&mut pending) == 0 && libc::sigismember(&pending, libc::SIGPIPE) == 1
    };
    // SAFETY: bytes is readable for its length; fd is a live nonblocking pipe.
    let result = count(unsafe { libc::write(fd, bytes.as_ptr().cast(), bytes.len()) });
    if result
        .as_ref()
        .is_err_and(|e| e.raw_os_error() == Some(libc::EPIPE))
        && !was_pending
    {
        let timeout = libc::timespec {
            tv_sec: 0,
            tv_nsec: 0,
        };
        // SAFETY: set/timeout are live; no siginfo storage is requested. Zero
        // timeout cannot block; SIGPIPE is still masked on this thread.
        unsafe {
            libc::sigtimedwait(&set, std::ptr::null_mut(), &timeout);
        }
    }
    // SAFETY: old was produced by the successful pthread_sigmask above.
    unsafe {
        libc::pthread_sigmask(libc::SIG_SETMASK, &old, std::ptr::null_mut());
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{io::Read, os::fd::FromRawFd, os::unix::net::UnixStream, time::Duration};
    #[tokio::test]
    async fn unicode_bytes_survive_partial_writes_and_backpressure() {
        let (sender, mut receiver) = UnixStream::pair().unwrap();
        receiver
            .set_read_timeout(Some(Duration::from_secs(2)))
            .unwrap();
        let bytes = "中文🟢é".repeat(32768).into_bytes();
        let expected = bytes.clone();
        let reader = tokio::task::spawn_blocking(move || {
            let mut out = Vec::new();
            receiver.read_to_end(&mut out).unwrap();
            out
        });
        let channel = Channel::new(sender.into()).unwrap();
        tokio::time::timeout(Duration::from_secs(2), channel.write(&bytes, || true))
            .await
            .unwrap()
            .unwrap();
        drop(channel);
        assert_eq!(reader.await.unwrap(), expected);
    }
    #[tokio::test]
    async fn stopped_authorization_has_no_write_and_a_stalled_consumer_is_cancellable() {
        let (sender, mut receiver) = UnixStream::pair().unwrap();
        receiver
            .set_read_timeout(Some(Duration::from_secs(1)))
            .unwrap();
        let channel = Channel::new(sender.into()).unwrap();
        assert!(
            channel
                .write(b"must not leave the process", || false)
                .await
                .is_err()
        );
        drop(channel);
        let mut out = Vec::new();
        receiver.read_to_end(&mut out).unwrap();
        assert!(out.is_empty());
        let (sender, _receiver) = UnixStream::pair().unwrap();
        let channel = Channel::new(sender.into()).unwrap();
        assert!(
            tokio::time::timeout(
                Duration::from_millis(30),
                channel.write(&vec![7u8; 4 * 1024 * 1024], || true)
            )
            .await
            .is_err()
        );
    }
    #[tokio::test]
    async fn broken_pipe_never_terminates_core_or_changes_the_thread_mask() {
        const CHILD: &str = "DOGCODES_CLIPBOARD_SIGPIPE_FIXTURE";
        if std::env::var(CHILD).as_deref() != Ok("pipe-v1") {
            let result = std::process::Command::new(std::env::current_exe().unwrap())
                .args(["--exact", "wayland::clipboard::io::tests::broken_pipe_never_terminates_core_or_changes_the_thread_mask", "--nocapture"])
                .env(CHILD, "pipe-v1").output().unwrap();
            assert!(
                result.status.success(),
                "SIGPIPE fixture failed: {:?}\n{}",
                result.status,
                String::from_utf8_lossy(&result.stderr)
            );
            return;
        }
        // SAFETY: only this isolated child executable changes the disposition;
        // it runs exactly this fixture and never hosts a user session.
        unsafe {
            libc::signal(libc::SIGPIPE, libc::SIG_DFL);
        }
        let mut fds = [-1; 2];
        // SAFETY: fds has space for two descriptors, owned on success.
        assert_eq!(unsafe { libc::pipe2(fds.as_mut_ptr(), libc::O_CLOEXEC) }, 0);
        // SAFETY: pipe2 returned two distinct live descriptors; each is adopted once.
        let (read, write) = unsafe { (OwnedFd::from_raw_fd(fds[0]), OwnedFd::from_raw_fd(fds[1])) };
        drop(read);
        // SAFETY: initialized writable storage receives this thread's mask.
        let mut before: libc::sigset_t = unsafe { std::mem::zeroed() };
        // SAFETY: a null set queries without changing the mask.
        let status =
            unsafe { libc::pthread_sigmask(libc::SIG_SETMASK, std::ptr::null(), &mut before) };
        assert_eq!(status, 0);
        let channel = Channel::new(write).unwrap();
        assert!(channel.write(b"x", || true).await.is_err());
        // SAFETY: initialized writable storage receives this thread's mask.
        let mut after: libc::sigset_t = unsafe { std::mem::zeroed() };
        // SAFETY: a null set queries without changing the mask.
        let status =
            unsafe { libc::pthread_sigmask(libc::SIG_SETMASK, std::ptr::null(), &mut after) };
        assert_eq!(status, 0);
        // SAFETY: before/after are initialized signal sets and SIGPIPE is valid.
        let before = unsafe { libc::sigismember(&before, libc::SIGPIPE) };
        // SAFETY: after is initialized and SIGPIPE is a valid signal.
        let after = unsafe { libc::sigismember(&after, libc::SIGPIPE) };
        assert_eq!(before, after);
    }
    #[test]
    fn regular_files_are_rejected_before_any_clipboard_write() {
        assert!(Channel::new(tempfile::tempfile().unwrap().into()).is_err());
    }
}
